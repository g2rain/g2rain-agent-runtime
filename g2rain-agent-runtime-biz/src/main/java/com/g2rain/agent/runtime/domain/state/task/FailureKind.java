package com.g2rain.agent.runtime.domain.state.task;


/**
 * 工具调用失败原因的稳定分类。
 *
 * <p>分类用于选择展示文案、恢复策略和审计统计，不代替工具返回的业务错误码。</p>
 *
 * @author alpha
 * @since 2026/9/9
 */
public enum FailureKind {

    /**
     * 无失败。
     * <p>调用成功或尚未判定失败时使用，作为证据上的缺省分类。</p>
     */
    NONE,

    /**
     * 鉴权失败。
     * <p>凭证无效、过期或无权调用目标系统。</p>
     */
    AUTH_FAILURE,

    /**
     * 参数不合法或缺失。
     * <p>入参校验未通过，通常可追问补参后重试。</p>
     */
    PARAMETER_FAILURE,

    /**
     * 业务失败。
     * <p>目标系统按规则拒绝，例如余额不足、单据不存在。</p>
     */
    BUSINESS_FAILURE,

    /**
     * 传输/网络失败。
     * <p>连不上或传输中断；工具是否已执行不确定时须先核查。</p>
     */
    TRANSPORT_FAILURE,

    /**
     * 限流。
     * <p>对端拒绝过快请求，可稍后重试而不是改参数。</p>
     */
    RATE_LIMIT,

    /**
     * 超时。
     * <p>在约定时限内没有完整结果；写工具超时不得直接当失败重放。</p>
     */
    TIMEOUT,

    /**
     * 未能归类。
     * <p>异常形态对不上上面几类时的兜底，便于审计而不是假装已知原因。</p>
     */
    UNKNOWN
}
